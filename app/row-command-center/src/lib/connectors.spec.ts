import { existsSync, readdirSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

import { describe, expect, it } from "vitest";

// Text-based checks. This app has taken ownership of src/lib/connectors.ts (the
// CLI's `@generated` marker was removed) and wires two connectors by hand, so we
// assert the file's shape as text rather than importing it — importing would pull
// in the connector entity classes' TC39 decorators, which the test transform does
// not parse (see connectorPermissions.test.ts for the same reason).

const appRoot = process.cwd();
const current = readFileSync(resolve(appRoot, "src/lib/connectors.ts"), "utf8").replace(/\r\n/g, "\n");

/** The scaffolded connector names (a dir under rayfin/connectors with a schema.ts). */
function scaffoldedConnectors(): string[] {
    const directory = resolve(appRoot, "rayfin/connectors");
    return existsSync(directory)
        ? readdirSync(directory, { withFileTypes: true })
            .filter((entry) => entry.isDirectory() && existsSync(resolve(directory, entry.name, "schema.ts")))
            .map((entry) => entry.name)
            .sort()
        : [];
}

describe("src/lib/connectors.ts (hand-owned wiring)", () => {
    it("keeps the app-owned block first", () => {
        expect(current.indexOf("// #region rayfin:app-owned")).toBe(0);
        expect(current).toContain("Copyright (c) Microsoft Corporation.");
        expect(current).toContain("export type SemanticModelConnectors");
    });

    it("has taken ownership — no CLI @generated marker remains", () => {
        expect(current).not.toContain("// @generated by `rayfin connector add`");
    });

    it("declares every scaffolded connector in AppConnectorsSchema and connectorConfigs", () => {
        for (const name of scaffoldedConnectors()) {
            expect(current).toContain(`'${name}':`);
        }
        // The two connectors this app ships.
        expect(current).toContain("'row_pbi_poc':");
        expect(current).toContain("'row-tracker':");
    });

    it("gives the semantic model a runtime, and the SQL connector none (Category A needs no runtime hook)", () => {
        const runtimesBlock = current.slice(current.indexOf("export const connectorRuntimes"));
        expect(runtimesBlock).toContain("'row_pbi_poc': fabricSemanticModel()");
        expect(runtimesBlock).not.toContain("'row-tracker':");
    });
});
